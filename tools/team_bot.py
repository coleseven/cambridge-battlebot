"""Compose the full bot: the strategy layer (bots/forager) with the trained fighter networks attached through
farming::combat_turn (combat_hook.h). Generated, so neither source tree is edited:

  bots/<out>/src = forager's src (strategy, draft, params.h)  +  the fighter (bots/neat/src/bot.cpp wrapped in
                   namespace fighter, with weights.h / genome.h / budget.h)  +  a baked genome.cpp
                   (tools/bake_fighter.py)  +  a main.cpp that installs fighter::take_turn as the combat hook.

  .venv/Scripts/python tools/team_bot.py --source champ:3 [--out team] [--macro-src bots/forager/src]
                                          [--fighter-src bots/neat/src] [--build]
Sources: champ:<N> (N-v-N champion set), neat:<run>, cgp:<run>, prior (hand prior, i.e. no networks).
tools/tune.py can then CMA-ES the strategy numbers in bots/<out>/src/params.h with the fighter attached.
"""
import argparse
import json
import struct
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import arena  # noqa: E402
import bake_fighter as bf  # noqa: E402
import league  # noqa: E402
import nvn  # noqa: E402

FIGHTER_FILES = ("weights.h", "genome.h", "budget.h", "order.h")

MAIN_CPP = '''// Generated by tools/team_bot.py: strategy layer (forager) + trained fighter via farming::combat_turn.
#include <cambc.h>
#include <iostream>
#include "bot.h"
#include "draft.h"
#include "combat_hook.h"
#include "fighter.h"
#include "params.h"
#include "win_model.h"

int main() {
    // Hand the turn to the fighter only when an enemy is within FIGHTER_ENGAGE_RANGE (params.h, tunable);
    // otherwise the strategy layer keeps it.
    farming::combat_turn = [] { return fighter::take_turn(FIGHTER_ENGAGE_RANGE); };
    if (FIGHTER_WIN_MODEL) farming::estimate_win = win_model::estimate;
    Bot bot;
    bool prepared = false;
    while (true) {
        try {
            if (cambc::is_draft()) {
                play_draft();
            } else {
                // The fighter's one-off setup (map fields) on each body's first turn, which has 2x fuel, so it
                // never lands on an ordinary turn the first time an enemy is seen.
                if (!prepared) {
                    prepared = true;
                    try { fighter::prepare(); } catch (const std::exception&) {}
                }
                bot.play_turn();
            }
        } catch (const std::exception& error) {
            std::cout << "bot error: " << error.what() << std::endl;
        } catch (...) {
            std::cout << "bot error: unknown exception" << std::endl;
        }
        cambc::end_turn();
    }
}
'''

FIGHTER_H = '''#pragma once
// Generated by tools/team_bot.py: the trained fighter as a library for the strategy layer's combat hook.
#include "order.h"
namespace fighter {
bool take_turn(int engage_range);   // fight this turn if an enemy is within range; true if it acted
bool take_order(const FighterOrder& order);   // fight this turn under the director's order; true if it acted
void prepare();     // one-off setup (fields, network); safe to call more than once
void warm();        // quiet-turn upkeep (objective field), so the rebuild seldom lands on a fight turn
}
'''


TAKE_TURN = '''

bool take_turn(int engage_range) {
    auto& me = c::self();
    const auto enemies = c::vision::champion_tiles(team::enemy);
    if (enemies.is_empty()) return false;
    c::bitboard near;
    near.clear();
    near.draw_chebyshev(me.position(), engage_range);
    if ((enemies & near).is_empty()) return false;   // nobody close: the strategy layer keeps the turn
    ACTED = false;
    play_turn_entry();
    return ACTED;
}

bool take_order(const FighterOrder& order) {
    ORDER = order;
    ACTED = false;
    play_turn_entry();
    ORDER = FighterOrder{};
    return ACTED;
}

'''


DRAFT_BLOCK = 16000          # word offset of the optional draft override inside the genome blob
DRAFT_MAGIC = 0x54465244     # 'DRFT'


def draft_override(src: str) -> str:
    """forager draft.cpp -> same, but a genome blob that carries a draft block (training: one composition per
    game, no rebuild) picks that composition instead of COMPS[DRAFT_COMP]. Without the block it is unchanged."""
    old = "    const auto& comp = COMPS[static_cast<std::size_t>(DRAFT_COMP) % COMPS.size()];"
    if src.count(old) != 1 or src.count('#include "params.h"\n') != 1:
        sys.exit("forager draft.cpp layout changed; update tools/team_bot.py")
    src = src.replace('#include "params.h"\n', '#include "params.h"\n#include "genome.h"\n')
    return src.replace(old, f"""    // Training override (tools/team_bot.py): picks written into the genome blob at word {DRAFT_BLOCK}.
    std::array<champion_draft, 5> override_comp{{}};
    const bool use_override = GENOME_BLOB[{DRAFT_BLOCK}] == 0x{DRAFT_MAGIC:08X}u;
    if (use_override)
        for (int i = 0; i < 5; ++i) override_comp[i] = static_cast<champion_draft>(GENOME_BLOB[{DRAFT_BLOCK} + 1 + i]);
    const auto& comp = use_override ? override_comp : COMPS[static_cast<std::size_t>(DRAFT_COMP) % COMPS.size()];""")


PARAM_BLOCK = 16008          # word offset of the optional runtime-params block (director sources)
PARAM_MAGIC = 0x534D5250     # 'PRMS'
PARAM_MAX = 64


def runtime_params(params_text: str, names) -> tuple[str, str]:
    """params.h text -> (same with `names` turned from constexpr into inline variables, params_runtime.h that
    loads them from a 'PRMS' block in the genome blob: [magic, n, value_0 .. value_n-1] as float bits, in the
    order of `names`; ints are rounded). Without the block the compiled defaults stay."""
    if len(names) > PARAM_MAX:
        raise ValueError("too many runtime params")
    types = {}
    for name in names:
        m = re.search(rf"^constexpr (\w+) {name} = ", params_text, re.M)
        if not m:
            sys.exit(f"runtime param {name} not in params.h")
        types[name] = m.group(1)
        params_text = params_text.replace(m.group(0), f"inline {m.group(1)} {name} = ", 1)
    sets = "\n".join(
        f"    if (n > {i}) {name} = " + (f"static_cast<{types[name]}>(std::lround(value({i})));" if types[name] != "float"
                                       else f"value({i});")
        for i, name in enumerate(names))
    loader = f"""#pragma once
// Generated by tools/team_bot.py --runtime-params: CMA-ES candidate values from the genome blob's 'PRMS' block
// (word {PARAM_BLOCK}: magic, count, then float bits in this order: {", ".join(names)}).
#include <cmath>
#include <cstdint>
#include <cstring>
#include "genome.h"
#include "params.h"
inline void params_runtime_load() {{
    if (GENOME_BLOB[{PARAM_BLOCK}] != 0x{PARAM_MAGIC:08X}u) return;
    const std::uint32_t n = GENOME_BLOB[{PARAM_BLOCK + 1}];
    auto value = [](int i) {{ const std::uint32_t w = GENOME_BLOB[{PARAM_BLOCK + 2} + i]; float v; std::memcpy(&v, &w, 4); return v; }};
{sets}
}}
"""
    return params_text, loader


def blob_with_params(blob: bytes, values) -> bytes:
    """A genome blob plus a 'PRMS' block holding `values` (floats, in the --runtime-params order)."""
    import struct
    words = list(struct.unpack(f"<{len(blob) // 4}I", blob))
    if len(words) > PARAM_BLOCK and any(words[PARAM_BLOCK:]):
        raise ValueError("blob already reaches the params block")
    words = words[:PARAM_BLOCK] + [0] * max(0, PARAM_BLOCK - len(words))
    words += [PARAM_MAGIC, len(values)] + [struct.unpack("<I", struct.pack("<f", float(v)))[0] for v in values]
    return struct.pack(f"<{len(words)}I", *words)


def blob_with_draft(blob: bytes, picks) -> bytes:
    """A genome blob (neat_train.blob) plus a draft block: picks = 5 champion_draft ids (0..10) in pick order."""
    import struct
    words = list(struct.unpack(f"<{len(blob) // 4}I", blob))
    tail = words[PARAM_BLOCK:] if len(words) > PARAM_BLOCK else []     # a params block survives
    if any(words[DRAFT_BLOCK:PARAM_BLOCK]):
        raise ValueError("genome programs reach the draft block")
    words = words[:DRAFT_BLOCK]
    words += [0] * (DRAFT_BLOCK - len(words)) + [DRAFT_MAGIC] + [int(p) for p in picks]
    if tail:
        words += [0] * (PARAM_BLOCK - len(words)) + tail
    return struct.pack(f"<{len(words)}I", *words)


def wrap_fighter(src: str) -> str:
    """bots/neat bot.cpp -> fighter_bot.cpp: everything after the includes inside namespace fighter."""
    src = src.replace('#include "bot.h"\n', '#include "fighter.h"\n')
    lines = src.split("\n")
    last_inc = max(i for i, l in enumerate(lines) if l.startswith("#include"))
    head, body = "\n".join(lines[:last_inc + 1]), "\n".join(lines[last_inc + 1:])
    if body.count("void Bot::play_turn() {") != 1 or body.count("    if (!best) return;\n") != 1:
        sys.exit("fighter bot.cpp layout changed; update tools/team_bot.py")
    body = body.replace("void Bot::play_turn() {", "void play_turn_entry() {")
    body = body.replace("    if (!best) return;\n", "    if (!best) return;\n    ACTED = true;\n")
    return (head + "\n\nnamespace fighter {\nbool ACTED = false;   // set when the fighter executes an option\n"
            + body + TAKE_TURN +
            "void prepare() {\n    if (!S.ready) init();\n}\n"
            "void warm() {\n    if (S.ready) refresh_objective();\n}\n}  // namespace fighter\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", default="champ:3")
    ap.add_argument("--out", default="team")
    ap.add_argument("--macro-src", default="bots/forager/src")
    ap.add_argument("--fighter-src", default="bots/neat/src")
    ap.add_argument("--build", action="store_true")
    ap.add_argument("--engage-range", type=int, default=4)
    ap.add_argument("--win-model", type=int, default=0)
    ap.add_argument("--director-net", default="", metavar="best.json",
                    help="director sources: bake a learned director network (tools/director_train.py best.json)")
    ap.add_argument("--runtime-params", default="", metavar="SPACE.json",
                    help="director sources: make these params (a CMA-ES space file) loadable from the genome blob")
    ap.add_argument("--set", nargs="*", default=[], metavar="NAME=VALUE",
                    help="override params.h values in the generated tree (e.g. NN_HEROES=4095 for training)")
    a = ap.parse_args()
    macro, fsrc = arena.ROOT / a.macro_src, arena.ROOT / a.fighter_src
    out = arena.ROOT / "bots" / a.out
    if out.exists() and not (out / "src" / "fighter.h").exists():
        sys.exit(f"{out} exists and was not generated by team_bot.py; refusing to overwrite")
    if (out / "src").exists():
        shutil.rmtree(out / "src")
    shutil.copytree(macro, out / "src")
    # A director source (bots/director) brings its own main.cpp and fighter params; the forager gets the hook.
    director = (macro / "director.h").exists()
    if not director:
        (out / "src" / "main.cpp").write_text(MAIN_CPP, encoding="utf-8")
    dc = out / "src" / "draft.cpp"
    dc.write_text(draft_override(dc.read_text(encoding="utf-8")), encoding="utf-8")
    pp = out / "src" / "params.h"
    if not director:
        pp.write_text(pp.read_text(encoding="utf-8") + "\n// ---- fighter integration (tools/team_bot.py) ----\n"
                      f"constexpr int FIGHTER_ENGAGE_RANGE = {a.engage_range};   // fighter takes the turn when an enemy is this close\n"
                      f"constexpr int FIGHTER_WIN_MODEL = {a.win_model};   // 1: the fight selector uses win_model.h\n",
                      encoding="utf-8")
    for kv in a.set:
        k, v = kv.split("=", 1)
        text, n = re.subn(rf"(constexpr \w+ {k} = )[^;]+;", rf"\g<1>{v};", pp.read_text(encoding="utf-8"))
        if n != 1:
            sys.exit(f"--set: {k} not found in params.h")
        pp.write_text(text, encoding="utf-8")
    if a.runtime_params:
        names = list(json.loads(Path(a.runtime_params).read_text(encoding="utf-8")))
        text, loader = runtime_params(pp.read_text(encoding="utf-8"), names)
        pp.write_text(text, encoding="utf-8")
        (out / "src" / "params_runtime.h").write_text(loader, encoding="utf-8")
    (out / "src" / "fighter.h").write_text(FIGHTER_H, encoding="utf-8")
    for f in FIGHTER_FILES:
        shutil.copy2(fsrc / f, out / "src" / f)
    (out / "src" / "fighter_bot.cpp").write_text(wrap_fighter((fsrc / "bot.cpp").read_text(encoding="utf-8")),
                                                 encoding="utf-8")
    if a.source == "prior":
        progs = {}
    elif a.source.startswith("champ:"):
        progs = nvn.champion_set(int(a.source.split(":")[1]))
    else:
        progs = league.programs(a.source, 3)
    _, words = bf.blob_words(progs, 0)
    if a.director_net:
        import director_train as dt
        net = json.loads(Path(a.director_net).read_text(encoding="utf-8"))
        data = dt.with_director(struct.pack(f"<{len(words)}I", *words), net["words"])
        words = list(struct.unpack(f"<{len(data) // 4}I", data))
    heroes = ", ".join(nvn.PICKS[p] for p in sorted(progs)) or "none (hand prior)"
    (out / "src" / "genome.cpp").write_text(bf.genome_cpp(words, f"team bot, source {a.source}, networks: {heroes}"),
                                            encoding="utf-8")
    clash = sorted(set(p.name for p in macro.iterdir()) & {"fighter_bot.cpp", "fighter.h", "genome.cpp",
                                                           *FIGHTER_FILES})
    if clash:
        print(f"warning: macro source already has {clash}; the fighter's versions replaced them")
    print(f"wrote {out / 'src'}: strategy from {a.macro_src}, fighter from {a.fighter_src}, networks {a.source}")
    if a.build:
        b = arena.build(out, a.out)
        print(f"built {b.path} ({b.hash})")


if __name__ == "__main__":
    main()
